// Post-build checks for dist/: links, metadata, preview safeguards, form labels
// and copy that must not appear. Exits non-zero on any error.

import { readFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(projectDir, 'dist');
const site = JSON.parse(await readFile(path.join(projectDir, 'src', 'site.json'), 'utf8'));
const basePath = `/${(process.env.BASE_PATH ?? '/').trim().replace(/^\/+|\/+$/g, '')}/`.replace('//', '/');

const requiredPages = [
  'index.html',
  'services/index.html',
  'services/business-accounts/index.html',
  'about-us/index.html',
  'contacts/index.html',
];

// External destinations the concept is allowed to link to.
const allowedHosts = new Set(['www.google.com']);

// Copy that must never reach a customer-facing page.
const bannedCopy = [
  [/\bAI\b|artificial intelligence|claude|chatgpt|generated by/i, 'mentions AI or development tools'],
  [/strathmere|welwyn|hertfordshire/i, 'carries over the wrong firm or location'],
  [/lorem ipsum|\bTODO\b|\bTBC\b|placeholder/i, 'contains placeholder text'],
  [/free (initial )?consultation|guarantee|no obligation/i, 'makes an unconfirmed offer or guarantee'],
  [/testimonial|5[- ]star|\brated\b|\baward/i, 'implies reviews or awards'],
  [/chartered|ICAEW|ACCA|\bAAT\b|\bCIOT\b|\bATT\b|certified|regulated by/i, 'claims a qualification or membership'],
  [/£\s?\d|\d+(\.\d+)?\s?%|per cent/i, 'quotes a price or rate'],
  [/founded|established in|since (19|20)\d\d|\d+\s+(staff|employees|offices|clients)/i, 'makes a historical or size claim'],
  [/xero|quickbooks|sage (accounting|software)|freeagent/i, 'names a software partnership'],
];

const errors = [];
const fail = (file, message) => errors.push(`${file}: ${message}`);

const files = (await readdir(distDir, { recursive: true }))
  .filter((file) => file.endsWith('.html'))
  .map((file) => file.split(path.sep).join('/'))
  .sort();
const html = new Map(await Promise.all(files.map(async (file) => [file, await readFile(path.join(distDir, file), 'utf8')])));

for (const page of requiredPages) {
  if (!html.has(page)) fail(page, 'required page is missing');
}

const idsIn = (source) => new Set([...source.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]));
const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
const decode = (value) => value.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const visibleText = (source) =>
  decode(
    source
      .replace(/<head>[\s\S]*?<\/head>/, '')
      .replace(/<(script|style|svg)[\s\S]*?<\/\1>/g, ' ')
      .replace(/<wbr>/g, '')
      .replace(/<[^>]+>/g, ' ')
      .replace(/&nbsp;| /g, ' ')
      .replace(/\s+/g, ' '),
  );

const titles = new Map();
const descriptions = new Map();

for (const [file, source] of html) {
  const urlPath = file === 'index.html' ? '/' : `/${file.replace(/index\.html$/, '')}`;
  const pageUrl = new URL(urlPath, 'https://preview.invalid');

  // Metadata
  if (!/<html lang="en-GB">/.test(source)) fail(file, 'missing lang="en-GB"');
  const title = source.match(/<title>([^<]*)<\/title>/)?.[1];
  const description = source.match(/<meta name="description" content="([^"]*)">/)?.[1];
  if (!title) fail(file, 'missing <title>');
  if (!description) fail(file, 'missing meta description');
  const productionTitle = decode(title ?? '').replace(/^Preview: /, '');
  if (productionTitle.length > 60) fail(file, `title is ${productionTitle.length} characters (aim for 60 or fewer)`);
  if (description && (decode(description).length < 70 || decode(description).length > 160)) {
    fail(file, `meta description is ${decode(description).length} characters (aim for 70–160)`);
  }
  titles.set(title, [...(titles.get(title) ?? []), file]);
  descriptions.set(description, [...(descriptions.get(description) ?? []), file]);

  const h1s = source.match(/<h1[\s>]/g) ?? [];
  if (h1s.length !== 1) fail(file, `has ${h1s.length} <h1> elements`);

  // Preview safeguards
  const hasNoindex = source.includes('<meta name="robots" content="noindex, nofollow">');
  const hasBanner = source.includes('Unofficial design concept — preview only.');
  if (site.preview && !hasNoindex) fail(file, 'preview page is missing noindex, nofollow');
  if (site.preview && !hasBanner) fail(file, 'preview page is missing the preview banner');
  if (site.preview && /rel="canonical"/.test(source)) fail(file, 'preview page should not declare a canonical URL');
  if (!site.preview && (hasNoindex || hasBanner)) fail(file, 'production page still has preview banner or noindex');

  // No third-party resources, embeds or tracking
  for (const [tag] of source.matchAll(/<(script|link|img|iframe|source|video|audio|embed|object)\b[^>]*>/g)) {
    if (/^<(iframe|embed|object)/.test(tag)) fail(file, `embedded content is not allowed: ${tag}`);
    const loadsResource = tag.startsWith('<link') && attr(tag, 'rel') !== 'canonical';
    const ref = attr(tag, 'src') ?? (loadsResource ? attr(tag, 'href') : undefined);
    if (ref && /^(https?:)?\/\//.test(ref)) fail(file, `loads a third-party resource: ${ref}`);
  }
  if (/gtag\(|googletagmanager|google-analytics|fbq\(|hotjar|clarity\.ms|plausible|matomo/i.test(source)) {
    fail(file, 'contains analytics or tracking code');
  }

  // Forms must stay in demonstration mode
  for (const [tag] of source.matchAll(/<form\b[^>]*>/g)) {
    if (attr(tag, 'action')) fail(file, 'form has an action, so it could transmit data');
    if (attr(tag, 'method') !== 'dialog') fail(file, 'demonstration form must use method="dialog" so it cannot submit');
    if (!source.includes('does not send, store or email')) fail(file, 'form is missing its demonstration notice');
  }
  if (!site.preview && /data-demo-form/.test(source)) {
    fail(file, 'production build still contains the demonstration form; connect a real, privacy-reviewed handler first');
  }

  // Every form control needs a label
  const labelFor = new Set([...source.matchAll(/<label[^>]*\sfor="([^"]+)"/g)].map((m) => m[1]));
  for (const [tag] of source.matchAll(/<(input|select|textarea)\b[^>]*>/g)) {
    if (attr(tag, 'type') === 'hidden') continue;
    const id = attr(tag, 'id');
    const wrapped = attr(tag, 'type') === 'radio' || attr(tag, 'type') === 'checkbox';
    if (!wrapped && !(id && labelFor.has(id))) fail(file, `form control has no label: ${tag}`);
  }
  for (const [label] of source.matchAll(/<label class="choice">[\s\S]*?<\/label>/g)) {
    if (!/<input[^>]*type="radio"/.test(label) || !/>\s*[^<\s][^<]*<\/label>$/.test(label)) {
      fail(file, `radio option is missing visible label text: ${label}`);
    }
  }

  // Links and fragments
  const ids = idsIn(source);
  for (const [tag] of source.matchAll(/<a\b[^>]*>/g)) {
    const href = attr(tag, 'href');
    if (href === undefined) {
      fail(file, `link without href: ${tag}`);
      continue;
    }
    const value = decode(href);
    if (/^(mailto|tel):/.test(value)) {
      if (value.startsWith('tel:') && value !== site.phoneHref) fail(file, `unexpected telephone link ${value}`);
      if (value.startsWith('mailto:') && value !== `mailto:${site.email}`) fail(file, `unexpected email link ${value}`);
      continue;
    }
    if (value.startsWith('#')) {
      if (value.length > 1 && !ids.has(value.slice(1))) fail(file, `in-page link to missing #${value.slice(1)}`);
      continue;
    }
    if (/^https?:\/\//.test(value)) {
      const host = new URL(value).host;
      if (!allowedHosts.has(host)) fail(file, `external link to unapproved host ${host}`);
      if (!/rel="noopener noreferrer"/.test(tag)) fail(file, `external link should use rel="noopener noreferrer": ${value}`);
      continue;
    }

    const target = new URL(value, pageUrl);
    let targetPath = target.pathname;
    if (targetPath.startsWith(basePath)) targetPath = `/${targetPath.slice(basePath.length)}`;
    const targetFile = targetPath.endsWith('/') ? `${targetPath.slice(1)}index.html` : targetPath.slice(1);
    if (!targetPath.endsWith('/') && !existsSync(path.join(distDir, targetFile))) {
      fail(file, `link to ${value} has no trailing slash and no matching file`);
      continue;
    }
    if (!html.has(targetFile) && !existsSync(path.join(distDir, targetFile))) {
      fail(file, `broken link ${value} (resolved to /${targetFile})`);
      continue;
    }
    if (target.hash && html.has(targetFile) && !idsIn(html.get(targetFile)).has(target.hash.slice(1))) {
      fail(file, `link ${value} points to a missing fragment`);
    }
  }

  // Asset references
  for (const [, ref] of source.matchAll(/\s(?:src|href)="([^"#?]+\.(?:css|js|svg|woff2))(?:\?[^"]*)?"/g)) {
    const resolved = new URL(ref, pageUrl).pathname;
    const relative = resolved.startsWith(basePath) ? resolved.slice(basePath.length) : resolved.slice(1);
    if (!existsSync(path.join(distDir, relative))) fail(file, `missing asset ${ref}`);
  }

  // Contact details present on every page (footer)
  const text = visibleText(source);
  for (const detail of [site.phone, site.email, site.streetAddress, site.postcode]) {
    if (!text.includes(detail)) fail(file, `missing contact detail "${detail}"`);
  }

  for (const [pattern, reason] of bannedCopy) {
    const match = text.match(pattern);
    if (match) fail(file, `${reason}: "…${text.slice(Math.max(0, match.index - 40), match.index + 40).trim()}…"`);
  }
}

for (const [title, pages] of titles) if (pages.length > 1) errors.push(`Duplicate title "${title}" on ${pages.join(', ')}`);
for (const [description, pages] of descriptions) {
  if (pages.length > 1) errors.push(`Duplicate description "${description}" on ${pages.join(', ')}`);
}

if (errors.length) {
  console.error(`✗ ${errors.length} problem${errors.length === 1 ? '' : 's'} found:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}
console.log(`✓ ${html.size} pages checked: links, metadata, preview safeguards, form labels and copy rules all pass.`);
